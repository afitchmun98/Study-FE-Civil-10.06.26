function assertVisibleScrollable(snapshot, label, width = 1440, height = 900) {
  assert.equal(snapshot.rootOpen, true, `${label}: dropdown should be open`);
  assert.equal(snapshot.panelHidden, false, `${label}: panel should not be hidden`);
  assert.equal(snapshot.panelStyle.visibility, "visible", `${label}: panel should be visible`);
  assert.equal(snapshot.panelStyle.pointerEvents, "auto", `${label}: panel should accept input`);
  assert.ok(snapshot.panelBounds.x >= 0 && snapshot.panelBounds.y >= 0 && snapshot.panelBounds.x + snapshot.panelBounds.width <= width + 1 && snapshot.panelBounds.y + snapshot.panelBounds.height <= height + 1, `${label}: panel should fit the viewport`);
  assert.ok(snapshot.listScrollHeight > snapshot.listClientHeight, `${label}: options should overflow`);
  assert.equal(snapshot.listOverflowY, "auto", `${label}: options should be scrollable`);
}
